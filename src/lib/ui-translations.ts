export function translateUiText(language: SupportedLanguage, value: string): string {
  if (language === 'en' || !value.trim()) return value;
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const text = value.trim();
  const exact = phrases[text]?.[language];
  if (exact) return `${leading}${exact}${trailing}`;
  for (const translator of dynamicTranslators) {
    const match = text.match(translator.pattern);
    if (match) return `${leading}${translator.render(match, language)}${trailing}`;
  }
  return value;
}
